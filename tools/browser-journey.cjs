const { chromium } = require('playwright');
const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const { createHash } = require('node:crypto');
// The checked-in October 29 edition is the fixed regression fixture.
const TARGET_URL = process.env.TNP_TEST_URL;
if (!TARGET_URL) throw new Error('Set TNP_TEST_URL to the site root, including its trailing slash');
const ARTIFACTS = process.env.TNP_TEST_ARTIFACTS || path.resolve('.cache/browser-journey');

(async () => {
  fs.mkdirSync(ARTIFACTS, { recursive: true });
  const browser = await chromium.launch({ headless: false, args: ['--mute-audio'] });
  const page = await browser.newPage({ viewport: { width: 1380, height: 980 } });
  const errors = [];
  page.on('pageerror', error => errors.push(error.message));
  try {
    await page.goto(TARGET_URL);
    await page.getByRole('heading', { name: 'Early signals. Useful details.' }).waitFor();
    const operationalStatus = /launch checklist|launch preview|private producer|pending approval|coming soon/i;
    assert.doesNotMatch(await page.locator('footer').innerText(), operationalStatus);
    await page.evaluate(() => document.fonts.ready);
    assert.ok(await page.evaluate(() => [...document.fonts].some(font => font.family.includes('Pixelify Sans') && font.status === 'loaded')));
    await page.screenshot({ path: path.join(ARTIFACTS, 'home-desktop.png'), fullPage: true });
    await page.locator('.archive').getByRole('link', { name: /October 29, 2026/ }).click();
    await page.getByLabel('Find something you missed').waitFor();
    assert.ok(page.url().includes('/2026/10/29/'));
    await page.goto(new URL('2026/10/29/#3', TARGET_URL).href);
    await page.waitForFunction(() => { const el=document.getElementById('3'); return el && el.getBoundingClientRect().top >= 0 && el.getBoundingClientRect().top < 100; });
    assert.match(await page.locator('.story:target h2').innerText(), /Redox/);
    assert.equal(await page.getByText('Why picked', { exact: true }).count(), 20);
    await page.reload();
    assert.match(await page.locator('.story:target h2').innerText(), /Redox/);
    assert.doesNotMatch(await page.locator('footer').innerText(), operationalStatus);
    await page.getByLabel('Find something you missed').fill('BooBench');
    await page.getByText('Jump to a story', { exact: false }).click();
    await page.getByRole('link', { name: /03Redox|03 Redox/ }).click();
    assert.equal(await page.locator('.story:visible').count(), 20, 'A same-fragment link must recover a filtered-out story');
    assert.match(await page.locator('.story:target h2').innerText(), /Redox/);
    await page.getByText('Jump to a story', { exact: false }).click();
    assert.equal(await page.locator('.story:visible').count(), 20);
    assert.match(await page.locator('.story').first().innerText(), /Odysseys/);
    assert.match(await page.locator('.story').last().innerText(), /Boo ?Bench/);
    const player = page.locator('audio');
    await page.waitForFunction(() => Number.isFinite(document.querySelector('audio')?.duration));
    const duration = await player.evaluate(element => element.duration);
    assert.ok(duration > 400 && duration < 660);
    await page.getByRole('button', { name: 'Play episode', exact: true }).press('Space');
    await page.waitForFunction(() => { const audio = document.querySelector('audio'); return !audio.paused && audio.currentTime > 0; });
    const seek = page.getByRole('slider', { name: 'Seek through episode' });
    await seek.press('Home');
    for (let i = 0; i < 6; i++) await seek.press('ArrowRight');
    await page.waitForFunction(() => document.querySelector('audio').currentTime > 5);
    await page.getByRole('button', { name: 'Pause episode', exact: true }).press('Space');
    assert.ok(await player.evaluate(element => element.paused));
    await page.getByRole('button', { name: 'Mute', exact: true }).click();
    assert.ok(await player.evaluate(element => element.muted));
    await page.getByRole('button', { name: 'Unmute', exact: true }).click();
    assert.ok(await player.evaluate(element => !element.muted));
    const volume = page.getByRole('slider', { name: 'Volume', exact: true });
    await volume.press('End');
    assert.equal(await player.evaluate(element => element.volume), 1);
    await volume.press('ArrowLeft');
    assert.ok(await player.evaluate(element => element.volume < 1));
    await page.getByRole('button', { name: 'Restart episode', exact: true }).click();
    assert.equal(await player.evaluate(element => element.currentTime), 0);
    await page.emulateMedia({ reducedMotion: 'reduce' });
    assert.equal(await page.locator('.reel').first().evaluate(element => getComputedStyle(element).transform), 'none');
    await page.locator('.listen').screenshot({ path: path.join(ARTIFACTS, 'cassette-desktop.png') });
    await page.locator('.story').first().getByText('Dated signal snapshots').click();
    await page.locator('.story').first().getByRole('heading', { name: 'Our snapshot' }).waitFor();
    assert.match(await page.locator('.story').first().innerText(), /143 likes/);
    assert.equal(await page.locator('.story').first().locator('.sources a').first().getAttribute('href'), 'https://odysseysbench.com/v2');
    await page.getByLabel('Find something you missed').fill('BooBench');
    assert.equal(await page.locator('.story:visible').count(), 1);
    assert.equal(await page.getByRole('status').innerText(), '1 of 20 stories');
    await page.getByRole('link', { name: 'Permalink to story 20' }).click();
    const permalink = page.url();
    await page.reload();
    assert.equal(page.url(), permalink);
    assert.equal(await page.locator('.story:visible').count(), 20);
    assert.equal(await page.locator('.story:target h2').count(), 1);
    const legacyId = await page.locator('.story').nth(2).getAttribute('data-story-id');
    await page.goto(new URL('episodes/2026-10-29/#' + legacyId, TARGET_URL).href);
    assert.match(await page.locator('.story:has(.legacy-anchor:target) h2').innerText(), /Redox/);
    await page.goto(permalink);
    await page.getByLabel('Find something you missed').fill('not-a-real-topic-unique-20393');
    assert.equal(await page.locator('.story:visible').count(), 0);
    await page.getByText('No stories match. Try another search or reset the filters.').waitFor();
    await page.getByRole('button', { name: 'Reset', exact: true }).click();
    assert.equal(await page.locator('.story:visible').count(), 20);
    await page.getByLabel('Topic', { exact: true }).selectOption('Local AI');
    assert.equal(await page.locator('.story:visible').count(), 2);
    await page.getByRole('button', { name: 'Reset', exact: true }).click();
    await page.getByRole('link', { name: 'Story data' }).click();
    await page.waitForURL('**/data/2026-10-29.json');
    const record = JSON.parse(await page.locator('body').innerText());
    assert.equal(record.stories.length, 20);
    assert.equal(record.audio.embedded_chapters, 22);
    assert.ok(record.audio.url.endsWith('-chapters.mp3'));
    assert.ok(Math.abs(record.audio.duration_seconds - duration) < 0.1);
    assert.equal(record.stories[0].observations[0].community.score, 143);
    assert.equal(record.production, undefined);
    await page.goto(permalink.split('#')[0]);
    const downloadReady = page.waitForEvent('download');
    await page.getByRole('link', { name: 'Download the MP3' }).click();
    const download = await downloadReady;
    const mp3Path = path.join(ARTIFACTS, download.suggestedFilename());
    await download.saveAs(mp3Path);
    const mp3 = fs.readFileSync(mp3Path);
    assert.equal(mp3.length, record.audio.bytes);
    assert.equal(createHash('sha256').update(mp3).digest('hex'), record.audio.sha256);
    await page.getByRole('link', { name: 'Transcript', exact: false }).click();
    await page.waitForURL('**/transcripts/2026-10-29.txt');
    const transcript = await page.locator('body').innerText();
    assert.match(transcript, /Boo ?Bench/);
    assert.ok(transcript.trim().endsWith('Thanks to Intelligrit for sponsoring this daily update.'));
    for (const width of [320, 390, 768]) {
      await page.setViewportSize({ width, height: 844 });
      await page.goto(TARGET_URL);
      assert.ok(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth));
      await page.screenshot({ path: path.join(ARTIFACTS, `home-${width}.png`), fullPage: true });
      await page.locator('.archive').getByRole('link', { name: /October 29, 2026/ }).click();
      assert.ok(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth));
      await page.getByRole('button', { name: 'Play episode', exact: true }).click();
      await page.waitForFunction(() => !document.querySelector('audio').paused);
      await page.getByRole('button', { name: 'Pause episode', exact: true }).click();
      await page.locator('.listen').screenshot({ path: path.join(ARTIFACTS, `cassette-${width}.png`) });
      await page.getByLabel('Find something you missed').fill('BooBench');
      assert.equal(await page.locator('.story:visible').count(), 1);
      await page.locator('.story:visible').getByText('Dated signal snapshots').click();
      await page.locator('.story:visible').getByRole('heading', { name: 'Our snapshot' }).waitFor();
      await page.screenshot({ path: path.join(ARTIFACTS, `story-${width}.png`), fullPage: true });
    }
    const direct = await browser.newPage({ viewport: { width: 390, height: 844 } });
    await direct.goto(new URL('2026/10/29#3', TARGET_URL).href);
    await direct.evaluate(() => document.fonts.ready);
    await direct.waitForFunction(() => { const el = document.getElementById('3'); return el && el.getBoundingClientRect().top >= 0 && el.getBoundingClientRect().top < 100; });
    assert.match(await direct.locator('.story:target h2').innerText(), /Redox/);
    await direct.screenshot({ path: path.join(ARTIFACTS, 'direct-story-3.png') });
    await direct.close();
    const fallback = await browser.newPage({ javaScriptEnabled: false });
    await fallback.goto(new URL('2026/10/29/', TARGET_URL).href);
    assert.ok(await fallback.locator('audio[controls]').isVisible());
    assert.ok(await fallback.locator('.cassette').isHidden());
    await fallback.close();
    const failed = await browser.newPage();
    await failed.route('**/*.mp3', route => route.abort('failed'));
    await failed.goto(new URL('2026/10/29/', TARGET_URL).href);
    await failed.getByRole('alert').waitFor();
    assert.match(await failed.getByRole('alert').innerText(), /could not load/);
    assert.ok(await failed.getByRole('link', { name: 'Download the MP3' }).isVisible());
    await failed.close();
    const logo = await browser.newPage({ viewport: { width: 256, height: 256 } });
    await logo.goto(new URL('assets/mark.svg', TARGET_URL).href);
    await logo.screenshot({ path: path.join(ARTIFACTS, 'logo-256.png') });
    await logo.setViewportSize({ width: 32, height: 32 });
    await logo.screenshot({ path: path.join(ARTIFACTS, 'logo-32.png') });
    await logo.close();
    assert.deepEqual(errors, []);
    const result = { result: 'passed', url: TARGET_URL, stories: record.stories.length,
      views: [1380, 320, 390, 768], audio_seconds: duration, checks: ['cassette-volume-mute-restart', 'reduced-motion', 'no-js-audio-fallback', 'audio-error-feedback', 'public-footer-copy', 'pixel-font', 'calendar-route', 'direct-story-three', 'legacy-route-hash', 'same-fragment-filter-recovery', 'visible-selection-notes', 'home-to-edition', 'audio-keyboard-play-seek-pause', 'source-provenance', 'search', 'category', 'empty-reset', 'permalink-reload', 'public-json', 'mp3-download-hash', 'transcript-signoff', 'mobile-overflow'], errors };
    fs.writeFileSync(path.join(ARTIFACTS, 'journey.json'), JSON.stringify(result, null, 2));
    console.log(JSON.stringify(result));
  } catch (error) {
    await page.screenshot({ path: path.join(ARTIFACTS, 'failure.png'), fullPage: true });
    throw error;
  } finally {
    await browser.close();
  }
})().catch(error => { console.error(error); process.exitCode = 1; });
